function buildDeck(): DeckCard[] {
  const deck: DeckCard[] = [];
  MAJOR.forEach((c) => {
    deck.push({
      id: `major-${c.num}`,
      title: `${c.num}. ${c.kr}`,
      badge: String(c.num),
      colorVar: '--navy',
      up: c.up,
      rev: c.rev,
    });
  });
  SUITS.forEach((s) => {
    MINOR_RANKS.forEach((r) => {
      deck.push({
        id: `${s.key}-${r.label}`,
        title: `${s.label} ${r.label}`,
        badge: s.mono,
        colorVar: `--el-${s.el}`,
        up: `${s.theme}: ${r.up}`,
        rev: `${s.theme}: ${r.rev}`,
      });
    });
  });
  return deck;
}

